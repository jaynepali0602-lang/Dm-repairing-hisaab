-- Run this entire script in Supabase Dashboard > SQL Editor > New query.
create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  description text not null,
  amount numeric(12,2) not null check (amount > 0),
  kind text not null check (kind in ('income','expense')),
  category text not null default 'Other',
  entry_date date not null default current_date,
  created_at timestamptz not null default now()
);
alter table public.transactions enable row level security;
drop policy if exists "Authenticated staff can read transactions" on public.transactions;
drop policy if exists "Authenticated staff can insert transactions" on public.transactions;
create policy "Authenticated staff can read transactions"
on public.transactions for select to authenticated using (true);
create policy "Authenticated staff can insert transactions"
on public.transactions for insert to authenticated with check (auth.uid() = user_id);
-- Only signed-in invited users can access rows. Disable public sign-ups in
-- Authentication > Settings. Invite staff from Authentication > Users > Add user.
-- Add delete/update policies only if you later want staff to edit or delete records.
